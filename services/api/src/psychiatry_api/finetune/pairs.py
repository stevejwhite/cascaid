"""Find each catalogue station's neighbouring facts, for boundary training lines.

Usage:
  uv run --project services/api --locked python -m psychiatry_api.finetune.pairs \\
      artifacts/finetune/data-v6/valid.jsonl \\
      artifacts/finetune/runs/student-0.6b-v6/eval/pred-valid.jsonl

Two signals, neither from evaluation data (docs/STUDENT-CROSS-CHECK-PLAN.md, part B):
- similarity: cosine similarity of the facts' question labels (mean embedding), with the
  embedding model the topic classifiers use;
- confusions: lines of the student's own validation split (training data held back from
  training) labelled with one fact where the student chose the other.
Writes data/training/boundaries/pairs.yaml.
"""

import argparse
import asyncio
import itertools
import json
from collections import Counter
from pathlib import Path

import numpy as np
import yaml

from psychiatry_api.cases import Case, load_cases
from psychiatry_api.config import ROOT, Settings
from psychiatry_api.evaluation.interpreter import SPEECH_CASES
from psychiatry_api.finetune.format import parse
from psychiatry_api.models.selection import embedding_model
from psychiatry_api.roleplay.classify import Embedder, classifier_cache

OUT = ROOT / "data/training/boundaries/pairs.yaml"
PER_STATION = 4  # the best-scoring pairs per station
MAX_PER_STATION = 5  # pairs confused at least REPEATED times are always kept, up to this
CONFUSION_BONUS = 0.04  # added to the similarity per confusion (one is weak evidence)
REPEATED = 2


def confusions(cases: dict[str, Case], valid: Path, predicted: Path) -> Counter:
    """Unordered fact pairs the student mixed up on single-fact validation lines."""
    found: Counter = Counter()
    rows = [json.loads(line) for line in valid.read_text().splitlines()]
    preds = [json.loads(line) for line in predicted.read_text().splitlines()]
    for row, pred in zip(rows, preds, strict=True):
        case = cases.get(row["meta"]["case_id"])
        if case is None or case.id in SPEECH_CASES:
            continue
        gold, said = parse(case, row["messages"][2]["content"]), parse(case, pred["output"])
        if gold is None or said is None or len(gold.asked) != 1:
            continue
        [fact] = gold.asked
        for other in said.asked - gold.asked:
            found[(case.id, *sorted((fact, other)))] += 1
    return found


async def similarities(cases: list[Case]) -> dict[tuple[str, str, str], float]:
    settings = Settings()
    embedder = Embedder(embedding_model(settings), classifier_cache(settings))
    scores = {}
    for case in cases:
        means = {}
        for fact in case.facts:
            vectors = await embedder.embed(list(fact.asked_about))
            mean = vectors.mean(axis=0)
            means[fact.id] = mean / np.linalg.norm(mean)
        for a, b in itertools.combinations(sorted(means), 2):
            scores[(case.id, a, b)] = float(means[a] @ means[b])
    return scores


def choose(case: Case, similar: dict, confused: Counter) -> list[dict]:
    pairs = list(itertools.combinations(sorted(f.id for f in case.facts), 2))

    def score(p):
        return similar[(case.id, *p)] + CONFUSION_BONUS * confused[(case.id, *p)]

    ranked = sorted(pairs, key=score, reverse=True)
    picked = ranked[:PER_STATION]
    repeated = [p for p in ranked[PER_STATION:] if confused[(case.id, *p)] >= REPEATED]
    picked += repeated[: MAX_PER_STATION - len(picked)]
    return [
        {
            "facts": list(p),
            "similarity": round(similar[(case.id, *p)], 3),
            "confusions": confused[(case.id, *p)],
        }
        for p in picked
    ]


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument("valid", type=Path)
    parser.add_argument("predicted", type=Path)
    args = parser.parse_args()
    cases = {c.id: c for c in load_cases()}
    catalogue = [c for c in sorted(cases.values(), key=lambda c: c.id) if c.id not in SPEECH_CASES]
    confused = confusions(cases, args.valid, args.predicted)
    similar = asyncio.run(similarities(catalogue))
    stations = {case.id: choose(case, similar, confused) for case in catalogue}
    OUT.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "# Neighbouring facts per catalogue station, for boundary training lines (Prompt H).\n"
        "# Generated by psychiatry_api.finetune.pairs from label similarity and the student's\n"
        "# confusions on its validation split (training data); no evaluation data used.\n"
    )
    OUT.write_text(header + yaml.safe_dump({"stations": stations}, sort_keys=False, width=100))
    total = sum(len(v) for v in stations.values())
    print(
        f"{total} pairs for {len(stations)} stations; {sum(confused.values())} confusions -> {OUT}"
    )


if __name__ == "__main__":
    main()
